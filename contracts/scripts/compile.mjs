/**
 * compiles the keys contract (and the test token) with the pinned solc, writes build/*.json, and exports the
 * keys ABI to the app as src/lib/keys-abi.ts so the frontend and the contract can never drift apart.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import solc from "solc";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sources = {
  "SocialLiquidKeys.sol": { content: readFileSync(join(root, "src/SocialLiquidKeys.sol"), "utf8") },
  "MockUSDC.sol": { content: readFileSync(join(root, "test/MockUSDC.sol"), "utf8") },
};
const input = {
  language: "Solidity",
  sources,
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "cancun",
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] } },
  },
};
const out = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (out.errors ?? []).filter((e) => e.severity === "error");
for (const e of out.errors ?? []) console[e.severity === "error" ? "error" : "warn"](e.formattedMessage);
if (errors.length) process.exit(1);

mkdirSync(join(root, "build"), { recursive: true });
for (const [file, name] of [["SocialLiquidKeys.sol", "SocialLiquidKeys"], ["MockUSDC.sol", "MockUSDC"]]) {
  const c = out.contracts[file][name];
  writeFileSync(join(root, "build", `${name}.json`), JSON.stringify({ abi: c.abi, bytecode: `0x${c.evm.bytecode.object}` }, null, 2));
}

const abi = out.contracts["SocialLiquidKeys.sol"].SocialLiquidKeys.abi;
const target = join(root, "..", "src/lib/keys-abi.ts");
writeFileSync(
  target,
  `/** generated by contracts/scripts/compile.mjs from contracts/src/SocialLiquidKeys.sol. do not edit by hand. */\nexport const KEYS_ABI = ${JSON.stringify(abi, null, 2)} as const;\n`,
);
console.log(`compiled with solc ${solc.version()}; abi written to src/lib/keys-abi.ts`);
